CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS pg_net WITH SCHEMA extensions;

-- -----------------------------------------------------------------------------
-- 1. Custom Enum Types
-- -----------------------------------------------------------------------------
DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'ticket_status') THEN CREATE TYPE public.ticket_status AS ENUM ( 'New', 'Triaged', 'In Progress', 'Resolved', 'Closed' ); END IF;    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'ticket_priority') THEN CREATE TYPE public.ticket_priority AS ENUM ( 'Low', 'Medium', 'High', 'Urgent' ); END IF;    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'ticket_category') THEN CREATE TYPE public.ticket_category AS ENUM ( 'Hardware', 'Software', 'Network', 'Access & IAM', 'Database & Cloud', 'Other' ); END IF; END $$;

-- -----------------------------------------------------------------------------
-- 2. Support Teams Table
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.support_teams (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name VARCHAR(120) NOT NULL UNIQUE,
  default_category public.ticket_category NOT NULL UNIQUE,
  escalation_email VARCHAR(255) NOT NULL,
  slack_channel VARCHAR(120),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- -----------------------------------------------------------------------------
-- 3. Tickets Table & Relational / State-Machine Constraints
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.tickets (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_number BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  title VARCHAR(255) NOT NULL,
  description TEXT NOT NULL,
  category public.ticket_category NOT NULL DEFAULT 'Other',
  priority public.ticket_priority NOT NULL DEFAULT 'Medium',
  status public.ticket_status NOT NULL DEFAULT 'New',
  requester_email VARCHAR(255) NOT NULL,
  team_id UUID REFERENCES public.support_teams(id) ON DELETE RESTRICT,
  sla_due_at TIMESTAMPTZ,
  resolution_notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CONSTRAINT chk_tickets_triaged_requires_team
    CHECK (status::text NOT IN ('Triaged', 'In Progress') OR team_id IS NOT NULL),

  CONSTRAINT chk_resolution_notes
    CHECK (
      status::text NOT IN ('Resolved', 'Closed')
      OR (resolution_notes IS NOT NULL AND char_length(trim(resolution_notes)) > 0)
    )
);

CREATE INDEX IF NOT EXISTS idx_tickets_status_sla
  ON public.tickets (status, sla_due_at)
  WHERE sla_due_at IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_tickets_team_id
  ON public.tickets (team_id);

-- -----------------------------------------------------------------------------
-- 4. Immutable Append-Only Audit Log (ticket_events)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ticket_events (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_id UUID NOT NULL REFERENCES public.tickets(id) ON DELETE CASCADE,
  actor VARCHAR(120) NOT NULL DEFAULT 'system:unknown',
  event_type VARCHAR(80) NOT NULL,
  previous_state VARCHAR(255),
  new_state VARCHAR(255),
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_ticket_events_ticket_id_created_at
  ON public.ticket_events (ticket_id, created_at ASC);

-- -----------------------------------------------------------------------------
-- 5. Dead-Letter Queue & Exponential Backoff Retry Table
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.webhook_dead_letters (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_id UUID REFERENCES public.tickets(id) ON DELETE CASCADE,
  channel VARCHAR(64) NOT NULL,
  endpoint_url TEXT,
  payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  error_message TEXT NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'pending_retry'
    CHECK (status IN ('pending_retry', 'resolved', 'dead_lettered')),
  attempt_count INTEGER NOT NULL DEFAULT 1,
  max_attempts INTEGER NOT NULL DEFAULT 5,
  next_retry_at TIMESTAMPTZ NOT NULL,
  last_attempted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  resolved_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_webhook_dead_letters_due_retries
  ON public.webhook_dead_letters (status, next_retry_at ASC)
  WHERE status = 'pending_retry';

CREATE INDEX IF NOT EXISTS idx_webhook_dead_letters_ticket_id
  ON public.webhook_dead_letters (ticket_id, created_at DESC);

-- -----------------------------------------------------------------------------
-- 6. Webhook Runtime Configuration Table (for pg_net Trigger)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.webhook_config (
  key VARCHAR(120) PRIMARY KEY,
  value TEXT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- -----------------------------------------------------------------------------
-- 7. Trigger: Strict Ticket State-Machine Guard
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_enforce_ticket_state_machine()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$ DECLARE v_allowed TEXT[]; v_old_status TEXT := OLD.status::text; v_new_status TEXT := NEW.status::text; BEGIN IF v_new_status = v_old_status THEN RETURN NEW; END IF;    CASE v_old_status WHEN 'New' THEN v_allowed := ARRAY['Triaged', 'Closed']; WHEN 'Triaged' THEN v_allowed := ARRAY['In Progress', 'Resolved', 'Closed']; WHEN 'In Progress' THEN v_allowed := ARRAY['Triaged', 'Resolved', 'Closed']; WHEN 'Resolved' THEN v_allowed := ARRAY['Closed', 'In Progress']; WHEN 'Closed' THEN v_allowed := ARRAY[]::TEXT[]; ELSE RAISE EXCEPTION 'Invalid current ticket status: "\%"', v_old_status USING ERRCODE = 'check_violation'; END CASE;    IF NOT (v_new_status = ANY(v_allowed)) THEN IF array_length(v_allowed, 1) IS NULL THEN RAISE EXCEPTION 'Illegal ticket state transition: "\%" -> "\%". Ticket is in terminal state "\%" and cannot be transitioned.', v_old_status, v_new_status, v_old_status USING ERRCODE = 'check_violation'; ELSE RAISE EXCEPTION 'Illegal ticket state transition: "\%" -> "\%". Allowed next states from "\%": [\%].', v_old_status, v_new_status, v_old_status, array_to_string(v_allowed, ', ') USING ERRCODE = 'check_violation'; END IF; END IF;    RETURN NEW; END; $$;

DROP TRIGGER IF EXISTS trg_enforce_ticket_state_machine ON public.tickets;
CREATE TRIGGER trg_enforce_ticket_state_machine
  BEFORE UPDATE OF status ON public.tickets
  FOR EACH ROW
  EXECUTE FUNCTION public.fn_enforce_ticket_state_machine();

-- -----------------------------------------------------------------------------
-- 8. Trigger: Enforce Append-Only Immutability on ticket_events
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_enforce_immutable_ticket_events()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$ BEGIN RAISE EXCEPTION 'ticket_events is an immutable append-only audit log (\% is not permitted)', TG_OP; END; $$;

DROP TRIGGER IF EXISTS trg_ticket_events_immutable ON public.ticket_events;
CREATE TRIGGER trg_ticket_events_immutable
  BEFORE UPDATE OR DELETE ON public.ticket_events
  FOR EACH ROW
  EXECUTE FUNCTION public.fn_enforce_immutable_ticket_events();

-- -----------------------------------------------------------------------------
-- 9. Trigger: Asynchronous pg_net Webhook on New Ticket Insertion
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_notify_ticket_created()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$ DECLARE v_webhook_url TEXT; v_webhook_secret TEXT; v_event_id UUID := gen_random_uuid(); v_payload JSONB; BEGIN SELECT value INTO v_webhook_url FROM public.webhook_config WHERE key = 'ticket_created_webhook_url';    SELECT value INTO v_webhook_secret FROM public.webhook_config WHERE key = 'ticket_created_webhook_secret';    IF v_webhook_url IS NULL OR trim(v_webhook_url) = '' THEN RETURN NEW; END IF;    v_payload := jsonb_build_object( 'event_id', v_event_id, 'event_type', 'ticket.created', 'occurred_at', NOW(), 'record', to_jsonb(NEW) );    PERFORM extensions.net.http_post( url := v_webhook_url, headers := jsonb_build_object( 'Content-Type', 'application/json', 'X-Webhook-Secret', COALESCE(v_webhook_secret, ''), 'X-Webhook-Event-Id', v_event_id::text ), body := v_payload );    INSERT INTO public.ticket_events ( ticket_id, actor, event_type, previous_state, new_state, metadata ) VALUES ( NEW.id, 'postgres:pg_net_trigger', 'WEBHOOK_DISPATCHED', NULL, 'dispatched', jsonb_build_object('event_id', v_event_id, 'target_url', v_webhook_url) );    RETURN NEW; END; $$;

DROP TRIGGER IF EXISTS trg_ticket_created_webhook ON public.tickets;
CREATE TRIGGER trg_ticket_created_webhook
  AFTER INSERT ON public.tickets
  FOR EACH ROW
  EXECUTE FUNCTION public.fn_notify_ticket_created();